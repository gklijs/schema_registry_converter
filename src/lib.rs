//! Encoders and decoders for Kafka messages using the [Confluent Schema Registry], compatible
//! with the [Confluent Java serializers], so the same data can be used from the JVM and Rust.
//!
//! An encoder resolves the schema through a `SubjectNameStrategy`, either the latest version of
//! a subject or a supplied schema it registers, and prefixes the encoded value with the schema
//! id. A decoder reads the schema id from the bytes and fetches that schema. Both cache the
//! schemas they resolved, so the registry is only called once per schema.
//!
//! [Confluent Schema Registry]: https://docs.confluent.io/platform/current/schema-registry/index.html
//! [Confluent Java serializers]: https://github.com/confluentinc/schema-registry
//!
//! # Features
//!
//! Each format is behind its own feature:
//!
//! | Feature | Encoder and decoder | Values |
//! |---|---|---|
//! | `avro` | `AvroEncoder`, `AvroDecoder` | `apache_avro` values, or structs with serde |
//! | `json` | `JsonEncoder`, `JsonDecoder` | `serde_json` values, validated with JSON Schema |
//! | `proto_raw` | `ProtoRawEncoder`, `ProtoRawDecoder` | protobuf bytes, e.g. from types generated by `prost` |
//! | `proto_decoder` | `ProtoDecoder` | `prost_reflect::DynamicMessage`s, for messages only known at runtime |
//! | `proto_encoder` | `ProtoEncoder` | `prost_reflect::DynamicMessage`s, or JSON in the protobuf JSON mapping |
//!
//! The async implementations are in `async_impl`, enabled by the default `futures` feature, the
//! blocking ones are in `blocking`, with the `blocking` feature. With the `easy` feature,
//! `async_impl` also has `Easy*` variants, which wrap the encoder or decoder in an `Arc`. The
//! `native_tls` (default) and `rustls_tls` features pick the TLS implementation of `reqwest`,
//! and with `middleware` the async client can use `reqwest-middleware`.
//!
//! # Schema ids in headers
//!
//! Besides the schema id prefix, every encoder and decoder supports the schema guid in a
//! `__key_schema_id` or `__value_schema_id` header, like Confluent's
//! `HeaderSchemaIdSerializer`, through their `_with_header_id` methods. This needs Confluent
//! Schema Registry 8.0 or later.
//!
//! # Errors
//!
//! Errors are an [`SRCError`](crate::error::SRCError). Its `retriable` tells whether calling
//! again might succeed, e.g. after a network failure; the library doesn't retry by itself. Its
//! `cached` tells whether the error is cached: non-retriable errors are, until
//! `remove_errors_from_cache` is called on the encoder or decoder. The underlying error, if any,
//! is its [`source`](std::error::Error::source).
